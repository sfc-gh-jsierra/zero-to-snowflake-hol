def render_block(b: dict) -> str:
    t = b["type"]
    if t == "text":
        return f'<div class="step-text">{b["html"]}</div>'
    if t == "code":
        lang = b.get("lang", "sql")
        label = f'<span class="code-label">{html.escape(b["label"])}</span>' if b.get("label") else ""
        return (
            f'<div class="code-block" data-language="{lang}">\n'
            f'  <div class="code-header"><span class="code-language">{lang.upper()}{label}</span>'
            '<div class="code-actions"><button class="btn-copy" onclick="copyCode(this)" title="Copiar codigo">Copiar</button></div></div>\n'
            f'  <pre><code>{highlight(b["code"].strip(chr(10)), lang)}</code></pre>\n</div>'
        )
    if t == "image":
        cap = f'<figcaption>{b["caption"]}</figcaption>' if b.get("caption") else ""
        return f'<figure class="step-figure"><img src="{b["src"]}" alt="{html.escape(b.get("caption", ""))}" loading="lazy">{cap}</figure>'
    if t in ("callout", "expected"):
        kind = "expected" if t == "expected" else b.get("kind", "info")
        title = b.get("title") or ("Que deberias ver" if t == "expected" else "Nota")
        return (
            f'<div class="callout callout-{kind}"><div class="callout-icon">{ICONS[kind]}</div>'
            f'<div class="callout-content"><strong class="callout-title">{title}</strong><p>{b["html"]}</p></div></div>'
        )
    raise ValueError(f"unknown block type {t}")


def render(spec: dict) -> tuple[str, str, int]:
    steps = spec["steps"]
    nav = "\n".join(
        f'        <a href="#step-{i}" class="step-nav-item" data-step="{i}"><span class="step-indicator">{i}</span>'
        f'<span class="nav-label">{html.escape(s.get("nav", s["title"]))}</span><span class="nav-min">{s["minutes"]}\'</span></a>'
        for i, s in enumerate(steps, 1)
    )
    tracker = (
        '<aside class="progress-tracker" id="progressTracker">\n'
        '    <div class="progress-header"><span>PROGRESO</span><span class="progress-percent">0%</span></div>\n'
        '    <div class="progress-bar"><div class="progress-fill" id="progressFill"></div></div>\n'
        f'    <nav class="steps-nav" id="stepsNav">\n{nav}\n    </nav>\n</aside>'
    )
    parts = ['<main class="steps-container" id="steps">']
    parts += [render_block(b) for b in spec.get("intro", [])]
    for i, s in enumerate(steps, 1):
        badge = s.get("badge", "SQL")
        body = "\n".join(render_block(b) for b in s["blocks"])
        resumen = f'<div class="step-resumen"><strong>En este paso:</strong> {s["resumen"]}</div>' if s.get("resumen") else ""
        crit = f'<div class="step-criterio"><strong>Criterio de exito:</strong> {s["criterio"]}</div>' if s.get("criterio") else ""
        parts.append(f"""
    <article class="step-card" id="step-{i}" data-step="{i}">
        <div class="step-header">
            <div class="step-number">{i}</div>
            <div class="step-info">
                <h2 class="step-title">{html.escape(s["title"])}</h2>
                <span class="step-duration">~{s["minutes"]} min</span>
            </div>
            <button class="step-toggle" aria-expanded="true"><svg viewBox="0 0 24 24"><path d="M7.41 8.59L12 13.17l4.59-4.58L18 10l-6 6-6-6 1.41-1.41z"/></svg></button>
        </div>
        <div class="step-content">
            <span class="modalidad-badge {badge.lower()}">{badge}</span>
            {resumen}
            {crit}
{body}
            <div class="step-actions"><button class="btn-check" onclick="markStepComplete({i})">Marcar paso {i} como completado</button></div>
        </div>
    </article>""")
    parts.append("</main>")
    return tracker, "\n".join(parts), len(steps)


def build(name: str) -> None:
    spec = json.loads((CONTENT / f"{name}.json").read_text())
    page = GUIA / spec["lab"]
    src = page.read_text()
    tracker, main, n = render(spec)
    src = re.sub(r'<aside class="progress-tracker".*?</aside>', lambda _: tracker, src, count=1, flags=re.S)
    src = re.sub(r'<main class="steps-container".*?</main>', lambda _: main, src, count=1, flags=re.S)
    src = re.sub(r'(Pasos completados</span><span class="summary-value">)\d+/\d+', rf"\g<1>{n}/{n}", src)
    src = re.sub(r"\n/\* figures \+ expected \(generated.*?(?=</style>)", "", src, count=1, flags=re.S)
    src = src.replace("</style>", FIG_CSS + VISUAL_CSS + "</style>", 1)
    src = re.sub(r'\n<script id="visual-layer">.*?</script>\n', "", src, flags=re.S)
    src = src.replace("</body>", VISUAL_JS + "</body>", 1)
    src = re.sub(r"<span>\d+ pasos</span>", f"<span>{n} pasos</span>", src)
    src = src.replace("(Run All del setup)", "(completaste el LAB 0)")
    page.write_text(src)
    total = sum(s["minutes"] for s in spec["steps"])
    print(f"{spec['lab']}: {n} pasos, {total} min")


if __name__ == "__main__":
    names = sys.argv[1:] or sorted(p.stem for p in CONTENT.glob("*.json"))
    for nm in names:
        build(nm)

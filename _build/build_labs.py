PY_KW = "import|from|def|return|for|in|if|elif|else|with|as|while|class|try|except|lambda|and|or|not|none|true|false|async|await|yield"
SH_KW = "cd|snow|pip|npm|npx|git|export|echo|install|app|deploy|setup|validate|open|teardown|streamlit"


def highlight(code: str, lang: str) -> str:
    """Tiny tokenizer: comments, strings, numbers, keywords. Output stays copy-safe (textContent unchanged)."""
    kw = {"sql": SQL_KW, "python": PY_KW, "bash": SH_KW}.get(lang)
    if not kw:
        return html.escape(code)
    cmt = r"--[^\n]*|/\*.*?\*/" if lang == "sql" else r"#[^\n]*"
    pat = re.compile(rf"(?P<c>{cmt})|(?P<s>'(?:[^'\\]|\\.)*'|\"(?:[^\"\\]|\\.)*\")|(?P<n>\b\d+(?:\.\d+)?\b)|(?P<k>\b(?:{kw})\b)|(?P<f>\b[A-Za-z_][\w$]*(?=\())", re.S | re.I)
    out, pos = [], 0
    for m in pat.finditer(code):
        out.append(html.escape(code[pos:m.start()]))
        out.append(f'<span class="tk-{m.lastgroup}">{html.escape(m.group())}</span>')
        pos = m.end()
    out.append(html.escape(code[pos:]))
    return "".join(out)


